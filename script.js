const header = document.querySelector('.site-header');
const revealItems = document.querySelectorAll('.reveal, .skill-card');
const copyDiscord = document.querySelector('#copy-discord');
const toast = document.querySelector('#toast');
const languageSelect = document.querySelector('#language-select');
const metaDescription = document.querySelector('meta[name="description"]');
let activeLanguage = 'id';

const getSavedLanguage = () => {
  try {
    return window.localStorage.getItem('ziva-language');
  } catch {
    return null;
  }
};

const saveLanguage = (language) => {
  try {
    window.localStorage.setItem('ziva-language', language);
  } catch {
    // The page still works when storage is blocked or opened from a local file.
  }
};

const translateTemplate = (value, variables = {}) => Object.entries(variables)
  .reduce((result, [key, replacement]) => result.replaceAll(`{${key}}`, replacement), value);

const applyLanguage = (requestedLanguage) => {
  const language = translations[requestedLanguage] ? requestedLanguage : 'id';
  const copy = translations[language];
  activeLanguage = language;

  document.documentElement.lang = language;
  document.title = copy.pageTitle;
  if (metaDescription) metaDescription.content = copy.pageDescription;

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;
    if (copy[key] !== undefined) element.textContent = copy[key];
  });

  document.querySelectorAll('[data-i18n-html]').forEach((element) => {
    const key = element.dataset.i18nHtml;
    if (copy[key] !== undefined) element.innerHTML = copy[key];
  });

  [
    ['data-i18n-aria-label', 'aria-label'],
    ['data-i18n-alt', 'alt'],
    ['data-i18n-title', 'title']
  ].forEach(([dataAttribute, targetAttribute]) => {
    document.querySelectorAll(`[${dataAttribute}]`).forEach((element) => {
      const key = element.getAttribute(dataAttribute);
      if (copy[key] !== undefined) element.setAttribute(targetAttribute, copy[key]);
    });
  });

  if (languageSelect) languageSelect.value = language;
  saveLanguage(language);
};

applyLanguage(getSavedLanguage() || 'id');

languageSelect?.addEventListener('change', (event) => {
  applyLanguage(event.target.value);
});

const setHeaderState = () => {
  header?.classList.toggle('is-scrolled', window.scrollY > 24);
};

setHeaderState();
window.addEventListener('scroll', setHeaderState, { passive: true });

if ('IntersectionObserver' in window) {
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add('is-visible');
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.14 });
  revealItems.forEach((item) => observer.observe(item));
} else {
  revealItems.forEach((item) => item.classList.add('is-visible'));
}

const showToast = (message) => {
  if (!toast) return;
  toast.textContent = message;
  toast.classList.add('is-visible');
  window.clearTimeout(showToast.timer);
  showToast.timer = window.setTimeout(() => toast.classList.remove('is-visible'), 2200);
};

copyDiscord?.addEventListener('click', async () => {
  const handle = copyDiscord.dataset.handle || 'v.ziva';
  const copy = translations[activeLanguage];
  try {
    await navigator.clipboard.writeText(handle);
    showToast(translateTemplate(copy.toastCopied, { handle }));
  } catch {
    showToast(translateTemplate(copy.toastFallback, { handle }));
  }
});

